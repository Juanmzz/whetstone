/**
 * `.wst/.gitignore` — per-machine runtime state `init` writes but that a clone
 * must never inherit committed. The reasoning is Whetstone's own (its top-level
 * `.gitignore` explains each of these three at length); restated here rather than
 * cited, per ADR-0004: a target repo has never heard of Whetstone's tree.
 *
 * `memory/signals.jsonl` is deliberately absent: that page is committed on
 * purpose, and an init-written gitignore that swallowed it would silently stop a
 * team from sharing the one thing this whole layer exists to accumulate.
 */
export function renderWstGitignore(): string {
  return `# Whetstone runtime state. Regenerated on every run, never commit it.

# Compiled check index: regenerable from ${DEFINITION_DIR}/checks/*.md via \`wst check --compile\`.
# A compiled artifact that can silently go stale is the same trap as trusting a
# version string for identity.
checks/_index.json

# The execution log: what a gate run did, minute by minute. Per-machine state,
# not a judgment a team shares, and committing it leaves the tree dirty right
# after every push, since the pre-push hook runs the gate and the gate writes
# this file.
events.jsonl

# Receipts are a derived cache: "check X passed on this exact input". Regenerable,
# and a stale one would claim a pass that never happened for the current code.
# Worse than stale if committed: a receipt authorises skipping a check, so every
# clone would inherit skips it never earned, one of them possibly a paid judge
# call.
receipts/
`;
}

/**
 * `.wst/.gitattributes` — how git must merge the files two workers append to at once.
 *
 * `wst prepare` exists to put N workers on one repository. `memory/signals.jsonl`
 * is append-only and committed on purpose, so every pair of concurrent workers
 * writes a new last line and git reports a conflict it cannot resolve: it sees two
 * edits to one region and cannot know the records are independent. Measured three
 * times in a single day on a real repo running five workers.
 *
 * Resolving it by hand is worse than tedious. Picking a side DISCARDS a signal
 * somebody recorded, and non-negotiable 4 forbids exactly that. `union` keeps both
 * sides' lines, which for an append-only log is not a heuristic but the correct
 * answer.
 *
 * WHY THIS IS SAFE HERE, and would not be everywhere. `union` concatenates the two
 * halves verbatim, so a file whose last line lacks a newline would come back with
 * two records fused into one unparseable line — and `parseSignalLog` fails closed
 * and loud, so that breaks the gate rather than degrading it. `shell/jsonl.ts`
 * removes the hazard at the source: `appendJsonl` always terminates with a
 * newline, and repairs a missing separator before appending.
 *
 * `memory/decisions.md` is the tempting second entry and is deliberately absent.
 * Its records are numbered, so two workers branching from one base both compute
 * "the next is adr-0011" and both write it. `union` would not conflict on that; it
 * would merge two different decisions carrying the same id, turning a loud failure
 * into a silent one. The fix there is to the numbering, and it is a decision.
 */
export function renderWstGitattributes(): string {
  return `# How git must merge the files more than one worker appends to.
# See ${DEFINITION_DIR}/memory/README.md for what each page is.

# Append-only, committed, and written by every worker at once. \`union\` keeps both
# sides' lines. Picking a side would discard a signal somebody recorded.
memory/signals.jsonl merge=union

# Also append-only: a retro adds an entry, it does not rewrite the ones before it.
memory/retro-log.md merge=union

# DELIBERATELY ABSENT: memory/decisions.md. Two workers each computing "the next
# id" write the same one, and \`union\` would merge two different decisions under a
# single id instead of conflicting on them. Changing a decision edits a line inside
# an entry that already exists, which \`union\` would then keep twice.
`;
}

/** Written at the worktree root by a worker, never committed to the branch. */
export const ROOT_GITIGNORE_ENTRIES: readonly string[] = Object.freeze([".wst-lane"]);

/**
 * The stanza `init` ensures is present in the target repo's OWN `.gitignore`.
 *
 * Unlike \`.wst/.gitignore\` this cannot be a plain generated file: \`.wst-lane\`
 * lives at the repo root, and almost every repo already has a root
 * \`.gitignore\` with content worth keeping. The shell reads it and appends only
 * what is missing (source: \`src/commands/init.ts\`) rather than treating a
 * pre-existing \`.gitignore\` as a collision.
 *
 * @param entries defaults to all of them; pass only the ones missing from a
 *   \`.gitignore\` that already has some of this stanza, so a re-run does not
 *   duplicate a line.
 */
export function renderRootGitignoreStanza(
  entries: readonly string[] = ROOT_GITIGNORE_ENTRIES,
): string {
  return `# Per-worktree state \`wst prepare\` writes into a leased worktree: the charter
# and the lane marker. Both belong to the worktree, not the branch, so a
# committed one would scope every clone to a single task, and a formatter's
# --check step would fail on a file nobody meant to check in.
${entries.join("\n")}
`;
}

export interface AgentsMdInput {
  readonly repoName: string;
  /** Full text of the generated constitution; its sections are inlined. */
  readonly constitution: string;
  /** Full text of the generated triage-rules.md; its table is inlined. */
  readonly triageRulesMd: string;
  readonly activeSkills: readonly string[];
  readonly checkIds: readonly string[];
}

/** Everything after the frontmatter and the H1. */
function bodyOf(markdown: string): string {
  const withoutFrontmatter = markdown.replace(/^---\n[\s\S]*?\n---\n/, "");
  return withoutFrontmatter.replace(/^#[^\n]*\n/, "").trim();
}

export function renderAgentsMd(input: AgentsMdInput): string {
  const skills = input.activeSkills
    .map((path) => {
      const name = path.split("/").pop() ?? path;
      const blurb = SKILL_BLURBS[name];
      return `- \`${DEFINITION_DIR}/${path}\`${blurb === undefined ? "" : ` — ${blurb}`}`;
    })
    .join("\n");

  const checks =
    input.checkIds.length > 0
      ? `The gate runs: ${input.checkIds.map((id) => `\`${id}\``).join(", ")}. Each one is a\n` +
        `file under \`${DEFINITION_DIR}/checks/\` explaining what it is for and what to do when it fails.`
      : `No checks are registered yet. Add one under \`${DEFINITION_DIR}/checks/<id>.md\` when a class of\n` +
        "mistake proves worth catching automatically — not before.";

  return `# ${input.repoName} — agent workflow

> **GENERATED from \`${DEFINITION_DIR}/\`. Do not edit by hand.** Everything below is a rendering of
> files under \`${DEFINITION_DIR}/\`, which is the source of truth. Editing \`AGENTS.md\` changes nothing
> durable: the next regeneration overwrites it, and the rule you meant to change is
> still whatever \`${DEFINITION_DIR}/\` says.
>
> Every section below names its source file explicitly rather than referring to itself,
> because the same sentence is true in its source and false here.

## Constitution

${bodyOf(input.constitution)}

## How changes are triaged

${bodyOf(input.triageRulesMd)}

## Verification

${checks}

## Active skills

Read the file before acting when its trigger matches. These are rules, not suggestions;
each one exists because something went wrong without it.

${skills}

## Recording what happens

This is the part that makes the rest improve rather than rot.

- **Something goes wrong** — the agent takes a wrong turn and gets corrected, or nearly
  does — append a line to \`${DEFINITION_DIR}/memory/signals.jsonl\`. The schema is in
  \`${DEFINITION_DIR}/memory/README.md\`. Log the small ones; they are the ones that reveal patterns.
- **A decision gets made** — add an entry to \`${DEFINITION_DIR}/memory/decisions.md\`, following
  the shape that page describes.
- **Periodically** — run a retro: read the signals logged since the last one, cluster
  them, and decide what each cluster earns (amend a triage rule, add or retire a check,
  sharpen a skill). Record the outcome in \`${DEFINITION_DIR}/memory/retro-log.md\`.

**The analysis is automatic; the write is not.** A human confirms every change to a
rule. Nothing in this repo rewrites its own standard.
`;
}
