/**
 * @param texts what the shell read off Whetstone's own `skills/`, keyed by `from`.
 *   Absent entries leave `contents` unset, which `auditSelfContained` reports as
 *   unaudited rather than clean.
 */
/**
 * A skill as it should land in someone else's repo.
 *
 * The rule travels; the argument that produced it does not. A changelog entry
 * says "v4 (adr-0014, sig-0041)" — a decision and a signal that exist in
 * Whetstone's record and in no bootstrapped repo, so every line of it is a
 * dangling reference under ADR-0004. It is replaced by one line naming where the
 * rule came from, and the target repo's own retro grows the log from there.
 *
 * The frontmatter stays: `version:` is what an update compares against.
 */
export function payloadSkill(text: string): string {
  const at = text.indexOf("\n## Changelog");
  if (at === -1) return text;

  const version = /^version:\s*(\d+)/m.exec(text)?.[1] ?? "1";
  return (
    `${text.slice(0, at)}\n## Changelog\n\n` +
    `- v${version} (init): copied from the Whetstone payload. Entries below this one are ` +
    `this project's own — what changed, and the signals that earned it.\n`
  );
}

export function skillCopies(texts?: ReadonlyMap<string, string>): readonly CopyRequest[] {
  return SKILL_FILES.map((name) => {
    const from = `skills/${name}`;
    const raw = texts?.get(from);
    const contents = raw === undefined ? undefined : payloadSkill(raw);
    return {
      from,
      to: `${DEFINITION_DIR}/skills/${name}`,
      ...(contents === undefined ? {} : { contents }),
    };
  });
}

/**
 * Which skills are ON at init: all of them.
 *
 * Deactivation is calibration, not deletion — a rule that does not apply to this
 * project still costs context every session it is loaded — and `wst.yaml` is
 * where it happens, by hand, listing the inactive ones as comments.
 *
 * WHAT USED TO BE HERE: `doc-locations` was switched off for a repo whose commit
 * log named one author, on the theory that a solo project has no team/personal
 * split. That was a guess about how a project WORKS read off a headcount, and
 * ADR-0016 took it out with the rest of the inference. Nothing asks for it now,
 * and "on" is the answer the old code already gave whenever the count was
 * missingFromRegistry: absence of evidence was never evidence of solo work.
 */
export function activeSkills(present?: readonly string[]): readonly string[] {
  // `present` is what the shell read off `.wst/skills/`.
  return present ?? SKILL_FILES.map((name) => `skills/${name}`);
}

export interface WstYamlInput {
  readonly backend: string;
  readonly skills: readonly string[];
  /** Namespace for any memory adapter. Derived from the repo, never shared. */
  readonly namespace: string;
}

export function renderWstYaml(input: WstYamlInput): string {
  const active = new Set(input.skills);
  const inactive = SKILL_FILES.map((n) => `skills/${n}`).filter((s) => !active.has(s));

  const lines = [
    "# Whetstone config. Generated by `wst init`; safe to edit by hand.",
    "version: 0",
    "agent: claude             # which adapter runs llm checks",
    `backend: ${input.backend}            # files = self-contained, git-native, zero deps`,
    "memory:",
    "  # Pins the namespace for any memory adapter. NEVER share a namespace with another",
    "  # project: cross-contaminated memory is worse than none, because it looks like recall.",
    `  namespace: ${JSON.stringify(input.namespace)}`,
    "retro:",
    "  suggest_after: 5        # signals",
    "skills:                   # ACTIVE skills — the emitter references only these",
    ...input.skills.map((s) => `  - ${s}`),
  ];

  if (inactive.length > 0) {
    lines.push(
      "  # Inactive for this project. The file is on disk either way — uncomment to enable.",
      ...inactive.map((s) => `  # - ${s}`),
    );
  }

  return `${lines.join("\n")}\n`;
}

export interface ConstitutionInput {
  readonly repoName: string;
  readonly date: string;
  readonly purpose: string;
  readonly risk: RiskProfile;
  readonly conventions: readonly string[];
  /** What the repo declares about itself. Read, never guessed. */
  readonly detected: StackFacts;
  /** What somebody SAID the project is built with. Null until anyone says. */
  readonly declared: string | null;
}

/**
 * The two halves of the stack section, kept visibly apart.
 *
 * Above the line is a sentence a person or a judge wrote and signed. Below it is
 * what `init` read, each item next to the file it came from. Merging them into
 * one bullet list is how "counted 40 `.ts` files" ends up reading exactly like
 * "the owner told us it is TypeScript".
 */
function stackSection(detected: StackFacts, declared: string | null): string {
  const stated =
    declared === null || declared.trim().length === 0
      ? "**Not stated.** `wst init` reads what this repo declares — its scripts, its lockfile —\n" +
        "and it does not guess what the code is written in. Fill this in; nothing downstream\n" +
        "depends on it, and a reader does."
      : declared.trim();

  const read = [
    `- **Package manager:** ${detected.packageManager ?? "not declared anywhere init could read"}`,
    `- **Tests:** ${detected.commands.test ?? "no runner declared"}`,
    `- **Typecheck:** ${detected.commands.typecheck ?? "none declared"}`,
    `- **Lint:** ${detected.commands.lint ?? "none declared"}`,
    `- **Test files present at init:** ${detected.hasTests ? "yes" : "no"}`,
  ].join("\n");

  return `${stated}\n\nRead off this repo's own files at init, and correctable here:\n\n${read}`;
}

export function renderConstitution(input: ConstitutionInput): string {
  const stackFacts = stackSection(input.detected, input.declared);

  const conventions =
    input.conventions.length > 0
      ? input.conventions.map((c) => `- ${c}`).join("\n")
      : [
          "- Code, configuration and comments in English.",
          "- Commit style not yet established — pick one and record it here.",
        ].join("\n");

  return `---
id: constitution
generated: ${input.date}
status: active
---
# ${input.repoName} — constitution

Governance for this project. Every other file under \`${DEFINITION_DIR}/\` is calibrated against it.

**\`${DEFINITION_DIR}/constitution.md\` is amended by an explicit human edit and by nothing else.** The retro may
propose changes to the triage rules, the skills and the checks; it never touches the
constitution. A project whose definition of "correct" can be rewritten by the tool that
enforces it does not have a definition of correct.

## Purpose

${input.purpose.trim()}

## Risk profile

${renderRiskProfile(input.risk)}

## Non-negotiables

1. Every rule in this repo carries a receipt — the signal or decision that created it.
   A rule nobody can trace is a rule nobody can retire.
2. State that matters is plain text in git. No rule depends on a server being up.
3. A judgment check earns its \`block\`. A deterministic check may block freely; a check
   that depends on a model's opinion is capped at a warning until it has been measured
   against known-good and known-bad examples and agreed with itself every time.
4. Corrections are appended, never overwritten. \`${DEFINITION_DIR}/memory/signals.jsonl\` is
   append-only; an ADR is superseded rather than rewritten.

## Stack facts

${stackFacts}

## Conventions

${conventions}
`;
}

/** The memory schema, restated in full — the first of the two consequences above. */
export const MEMORY_README = `# Memory — how to log

This directory is the project's memory. It is plain text in git, it is append-only,
and it is the input to every retro. **Everything an agent needs in order to log
correctly is written down here** — there is nothing to look up elsewhere.

## \`signals.jsonl\` — append-only, one JSON object per line

A signal is a moment the agent went off-track and got corrected, or a near-miss. Log
the small ones too; that is the point. A retro over five sharp signals produces a real
rule, a retro over none produces a plausible one.

| field | required | notes |
|-------|----------|-------|
| \`id\` | yes | \`sig-\` + zero-padded counter, e.g. \`sig-0001\` |
| \`ts\` | yes | ISO 8601 datetime |
| \`type\` | yes | kebab-case, open vocabulary: \`wrong-cwd\`, \`triage-miss\`, \`test-skip\`, \`scope-creep\`, \`context-blowout\`, … |
| \`phase\` | yes | \`init\` \\| \`triage\` \\| \`plan\` \\| \`apply\` \\| \`verify\` \\| \`review\` \\| \`other\` |
| \`severity\` | yes | \`low\` \\| \`medium\` \\| \`high\` |
| \`detail\` | yes | one or two sentences a human can reconstruct the event from |
| \`branch\` | no | the git branch it happened on — the unit of work. Read from git, never guessed from a ticket id. Omit it rather than writing \`null\` |
| \`rule_affected\` | no | skill file(s) implicated, e.g. \`["skills/delegation.md"]\` |
| \`supersedes\` | no | id of an earlier entry this one corrects |
| \`resolved_by\` | no | filled by the retro: the amendment that addressed this signal |

**Never edit or delete a line.** A correction is a NEW entry carrying \`supersedes\`.
The one exception is \`resolved_by\`, which the retro may set on an existing line — it
records which amendment answered the signal, not what happened.

Example:

\`\`\`
{"id":"sig-0001","ts":"2026-01-15T14:30:00Z","type":"wrong-cwd","phase":"apply","severity":"high","detail":"Sub-agent ran a destructive command at the repo root instead of the package directory.","branch":"feat/import-csv","rule_affected":["skills/delegation.md"]}
\`\`\`

## \`decisions.md\` — one anchored entry per decision

\`### adr-NNNN — the decision\`, then a meta line carrying status, date and any signals
that earned it, then **what was rejected and why**. That last part is the reason the
record exists: a rejected option leaves no commit, so git cannot reconstruct it. The
page itself says the rest.

**Accepted text is never rewritten.** A decision that turned out wrong is superseded —
its status moves, its prose stays. The value of the record is that it shows what was
believed at the time, and editing it destroys exactly that.

## \`out-of-scope/\` — what was deliberately refused

One file per capability this project was asked for and decided not to build. A
refusal that lives only in memory gets re-proposed every few months with the
argument re-derived from scratch. Each entry says what was asked, why it is out of
scope, what escape hatches already exist, and the request that prompted it. Empty
until something is actually refused; the directory's own README has the form.

## \`patterns.md\` and \`retro-log.md\`

\`patterns.md\` holds distilled recurring patterns — the output of a retro, not raw
observation. \`retro-log.md\` records that a retro happened, which signals it read, and
what it changed, so the next one knows where to start.

## The loop

Signals are data; decisions are prose. Both feed the retro: read the new signals,
cluster them, and decide what apparatus each cluster earns — amend a rule, add a check,
retire one that never fires. **The analysis is automatic; the write is not.** A human
confirms every change to a rule, because a tool that can silently rewrite the standard
it enforces against you is not a standard.
`;

